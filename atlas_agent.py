    def generate_json_str(self, result):
        """
        analyze the datasets generated by LLMs
        """
        result = result[result.index("{"):]
        last_index = -1
        for i in range(len(result)):
            if result[i] == '}':
                last_index = i
        result = result[:last_index+1]
        result = json.loads(result)
        ###sort result json dict
        sorted_items = sorted(result.items(), key=lambda x: x[1], reverse=True)[:3]
        result_fun = ""
        for fun in sorted_items:
            result_fun += fun[0] + " "
        return result_fun
    
    def evaluate_image_data(self, image_path, output_excel=None, is_dir=False):
        """
        generate the result for image/image path(for multiple images)
        """
        prompt = '''
                    SYSTEM
                    You are a senior single-cell bioinformatician.
                    
                    INPUT
                    • One composite figure.  Upper row: projection coloured by BATCH.  Lower row: projection coloured by CELL TYPE.  
                    • The left-most tile is “Unintegrated”; the remaining tiles are candidate methods.
                    
                    VISUAL RUBRIC  (0 = poor, 5 = excellent)
                    M1  Batch mixing          – batch colours well intermixed inside clusters.
                    M2  Graph connectivity    – biologically related clusters remain weakly bridged.
                    M3  Cell-type silhouette  – cluster borders are crisp, single-coloured.
                    M4  Cell-type continuity  – each cell type forms one contiguous island.
                    
                    Score each method.  
                    Compute total = 0.25(M1+M2+M3+M4).  
                    
                    ### output
                    only return the sorted json for all methods and its score. 
                    example: {"method 1": 4.0, "method 2": 3.5 ....}
                    ###Do not return any details of score, only output the json
                    '''
        if not is_dir:
            #generate for single image
            buffer = self.compress_image(image_path, quality=100)
            base64_image = base64.b64encode(buffer.read()).decode('utf-8')
            data = self.run_gpt_api(prompt, base64_image)
            result_functions = self.generate_json_str(data)
            return result_functions
        else:
            files = [os.path.join(image_path, f) for f in os.listdir(image_path) if os.path.isfile(os.path.join(image_path, f))]
            all_dict = {}
            for image in files:
                buffer = self.compress_image(image, quality=100)
                base64_image = base64.b64encode(buffer.read()).decode('utf-8')
                data = self.run_gpt_api(prompt, base64_image)
                result_functions = self.generate_json_str(data)
                all_dict[image.replace(image_path, "")] = result_functions
            df = pd.DataFrame(list(all_dict.items()), columns=['image', 'top 3 methods'])
            df.to_excel(output_excel, index=False)
            return all_dict

